window.onload = function() {
  showCafeteria();
  showOrganizations();

  var cafSearchElem = document.getElementById("cafSearch");
  var cafCatElem = document.getElementById("cafCategory");
  var orgSearchElem = document.getElementById("orgSearch");
  var orgCatElem = document.getElementById("orgCategory");

  if (cafSearchElem) cafSearchElem.addEventListener("keyup", showCafeteria);
  if (cafCatElem) cafCatElem.addEventListener("change", showCafeteria);
  if (orgSearchElem) orgSearchElem.addEventListener("keyup", showOrganizations);
  if (orgCatElem) orgCatElem.addEventListener("change", showOrganizations);
};