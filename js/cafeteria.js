function switchTab(viewName) {
  var cafSection = document.getElementById("cafeteriaSection");
  var orgsSection = document.getElementById("orgsSection");

  var btnCaf = document.getElementById("tabBtnCaf");
  var btnOrgs = document.getElementById("tabBtnOrgs");
  var btnAll = document.getElementById("tabBtnAll");

  if (!cafSection || !orgsSection) return;

  if (btnCaf) btnCaf.className = "tab-btn";
  if (btnOrgs) btnOrgs.className = "tab-btn";
  if (btnAll) btnAll.className = "tab-btn";

  if (viewName === "cafeteria") {
    cafSection.style.display = "block";
    orgsSection.style.display = "none";
    if (btnCaf) btnCaf.className = "tab-btn active";
  } else if (viewName === "orgs") {
    cafSection.style.display = "none";
    orgsSection.style.display = "block";
    if (btnOrgs) btnOrgs.className = "tab-btn active";
  } else {
    cafSection.style.display = "block";
    orgsSection.style.display = "block";
    if (btnAll) btnAll.className = "tab-btn active";
  }
}

function showCafeteria() {
  var container = document.getElementById("cafeteriaList");
  var searchElem = document.getElementById("cafSearch");
  var categoryElem = document.getElementById("cafCategory");

  if (!container || !searchElem || !categoryElem) return;

  var searchInput = searchElem.value.toLowerCase();
  var categoryInput = categoryElem.value;
  var htmlContent = "";

  for (var i = 0; i < stalls.length; i++) {
    var item = stalls[i];

    var matchesSearch = item.name.toLowerCase().indexOf(searchInput) !== -1 ||
                          item.menu.toLowerCase().indexOf(searchInput) !== -1;
    var matchesCategory = (categoryInput === "all") || (item.floor === categoryInput);

    if (matchesSearch && matchesCategory) {
      htmlContent += '<div class="card">';
      htmlContent += '  <span class="badge">' + item.floorLabel + '</span>';
      htmlContent += '  <h3>' + item.name + '</h3>';
      htmlContent += '  <p><strong>Menu & Offers:</strong> ' + item.menu + '</p>';
      htmlContent += '  <div class="location-images">';
      htmlContent += '    <div class="img-placeholder">';
      htmlContent += '      <img src="' + item.image1 + '" alt="Stall Photo 1" onerror="this.style.display=\'none\'; this.nextElementSibling.style.display=\'block\';">';
      htmlContent += '      <span class="img-label" style="display:none;">Stall Photo 1</span>';
      htmlContent += '    </div>';
      htmlContent += '    <div class="img-placeholder">';
      htmlContent += '      <img src="' + item.image2 + '" alt="Stall Photo 2" onerror="this.style.display=\'none\'; this.nextElementSibling.style.display=\'block\';">';
      htmlContent += '      <span class="img-label" style="display:none;">Stall Photo 2</span>';
      htmlContent += '    </div>';
      htmlContent += '  </div>';
      htmlContent += '</div>';
    }
  }

  if (htmlContent === "") {
    container.innerHTML = '<p style="font-size: 14px; color: #888;">No cafeteria stalls found.</p>';
  } else {
    container.innerHTML = htmlContent;
  }
}

